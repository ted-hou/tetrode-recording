for i = 1:length(si)
    sessionInfo = struct(...
        expName=si{i, 1}, ...
        strain=si{i, 2}, ...
        facing=si{i, 3}, ...
        ml=si{i, 4}, ...
        dv=si{i, 5}, ...
        ap=si{i, 6}, ...
        probe=si{i, 7}, ...
        duraOffset=-200);

    ar = AcuteRecording(sessionInfo, useNewProbeMap=true);
    ar.save('ar_', 'C:\SERVER\Acute\Reach2tgt')
end



%% ChannelMapping: 
ar = AcuteRecording.load('C:\SERVER\Acute\Reach2tgt\AcuteRecording');
euReachDir2Tgt = EphysUnit.load('C:\SERVER\Units\acute_DA\DA new');

%% Find location of units from AR
euPos = NaN(length(euReachDir2Tgt), 3); % ml dv ap
for iEu = 1:length(euReachDir2Tgt)
    iAr = find(strcmpi(euReachDir2Tgt(iEu).ExpName, {ar.expName}));
    if ~isempty(iAr)
        euPos(iEu, :) = ar(iAr).getProbeCoords(euReachDir2Tgt(iEu).Channel);
        c.hasPos(iEu) = true;
    else
        fprintf(1, 'Cannot find AR: %s\n', euReachDir2Tgt(iEu).ExpName)
    end
end

%% Plot channel map
plot3(abs(euPos(:, 1)), euPos(:, 3), euPos(:, 2), 'o')
